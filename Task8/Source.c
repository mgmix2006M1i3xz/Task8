int word1() {
    int count;
    char sym;

    printf("Введите количество символов: ");
    scanf("%d", &count);
    printf("Введите символ для печати: ");
    // Пробел перед %c нужен, чтобы пропустить символ новой строки после scanf %d
    scanf(" %c", &sym);

    // *) Напечатайте в начале и/или в конце символ '+'
    putchar('+');

    // ***) Печатайте после каждого символа восклицательный знак!
    // **) Напечатайте полстроки одним символом, а вторую половину другим.

    int half = count / 2; // Вычисляем половину

    for (int start = 1; start <= count; start++) {
        // **) Меняем символ во второй половине на другой (например, '#')
        if (start > half) {
            putchar('#'); // Первую половину печатаем введенным символом, вторую - решеткой
        }
        else {
            putchar(sym);
        }

        // ***) Добавляем '!' после каждого символа
        putchar('!');
    }

    // *) Символ '+' в конце
    putchar('+');
    printf("\n");

    return 0;
}

int word2() {
    
    int n, m;
    int s = 0;      // Переменная для накопления суммы (инициализируем нулем!)
    int k = 1;      // Счетчик итераций для вывода

    // Шаг 2. Ввод значений
    printf("Введите начальное число m (большее): ");
    scanf("%d", &m);
    printf("Введите конечное число n (меньшее): ");
    scanf("%d", &n);

    // Шаг 3, 4, 5. Цикл (инициализация; условие; модификация)
    for (int i = m; i >= n; i--) {
        // Шаг 6. Накопление результата и вывод итераций
        s += i;
        printf("выполнено %d раз (текущее i = %d)\n", k++, i);
    }

    printf("\nРезультат суммы: %d\n", s);

    return 0;
}

int word3() {
    int n;
    printf("Введите максимальную степень n: ");
    scanf("%d", &n);

    printf("Значения 2 в степени от 0 до %d:\n", n);

    // Печатаем в столбик
    for (int i = 0; i <= n; i++) {
        // Используем тип double для pow, чтобы избежать переполнения на больших числах
        printf("2^%d = %.0f\n", i, pow(2, i));
    }

    return 0;
}

int word4() {
    float x_start = 2.0, x_end = 4.0;
    float step, x, y;

    // 1) Приглашение к вводу с указанием функции
    printf("Программа табулирования функции: y = 2^x - 2x^2 - 1\n");
    printf("Диапазон: [2; 4]\n");

    // 2) Ввод шага табуляции
    printf("Введите шаг табуляции (например, 0.5): ");
    scanf("%f", &step);

    // Проверка на корректность шага
    if (step <= 0) {
        printf("Ошибка: шаг должен быть больше нуля!\n");
        return 1;
    }

    // 3) Оформление результатов в виде таблицы
    printf("\n-------------------\n");
    printf("|   x   |   f(x)   |\n");
    printf("-------------------\n");

    // Цикл с параметром. Идем от x_start до x_end с шагом step
    for (x = x_start; x <= x_end; x += step) {
        
        y = pow(2, x) - 2 * pow(x, 2) - 1;

        // Вывод строки таблицы
        printf("| %5.2f | %8.3f |\n", x, y);
    }
    printf("-------------------\n");

    return 0;
}

int word5() {
    int n;
    double sum = 0.0;

    printf("Введите значение n для вычисления суммы ряда: ");
    scanf("%d", &n);

    // Цикл от 0 до n включительно
    for (int i = 0; i <= n; i++) {
        // Вычисляем текущий член ряда: (-1)^i * (1 / 2^i)
        // pow(-1, i) даст 1 для четных i и -1 для нечетных
        double term = pow(-1, i) * (1.0 / pow(2, i));

        // Добавляем к общей сумме
        sum += term;

        // Для наглядности можно выводить текущий член (опционально)
        // printf("Член %d: %f\n", i, term);
    }

    printf("Сумма ряда при n = %d равна: %lf\n", n, sum);

    return 0;
}

